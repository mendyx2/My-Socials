import { loadEnv } from "./env";
import { runIdeasPipeline } from "../src/lib/pipeline";

loadEnv();

const countArg = process.argv.find((a) => a.startsWith("--count="));
const count = countArg ? Number(countArg.split("=")[1]) : undefined;

try {
  const r = await runIdeasPipeline({ count });
  const failed = r.feeds.filter((f) => !f.ok);
  console.log(`✅ ${r.ideas.length} ideas generated by ${r.generatedBy}`);
  console.log(`   News: ${r.newsRead} read, ${r.newsUsed} sent to the AI. Feeds OK: ${r.feeds.length - failed.length}/${r.feeds.length}`);
  if (r.dropped) console.log(`   ${r.dropped} malformed idea(s) dropped`);
  if (r.skippedProviders.length) console.log(`   Skipped providers: ${r.skippedProviders.join(", ")}`);
  for (const f of failed) console.log(`   ⚠️  ${f.feed.name}: ${f.error}`);
  if (r.digestPath) console.log(`   Digest: ${r.digestPath}`);
  for (const [i, idea] of r.ideas.entries()) console.log(`\n${i + 1}. [${idea.format}] ${idea.title}\n   ${idea.hook}`);
} catch (err) {
  console.error(`❌ ${(err as Error).message}`);
  process.exit(1);
}
