// Bakes profile/*.md into the app as starting content, so a fresh hosted site isn't empty.
// Whatever you save in the app takes priority. Runs automatically before every build.
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const FILES = ["about.md", "pillars.md", "brand.md", "voice.md", "updates.md"];
const defaults = Object.fromEntries(FILES.map((f) => [f, existsSync(`profile/${f}`) ? readFileSync(`profile/${f}`, "utf8") : ""]));
writeFileSync(
  "src/lib/kb-defaults.generated.ts",
  `// Generated by scripts/gen-kb-defaults.ts from profile/*.md. Do not edit.\nexport const KB_DEFAULTS: Record<string, string> = ${JSON.stringify(defaults, null, 2)};\n`,
);
console.log(`Baked ${FILES.length} knowledge-base files.`);
