import type { FeedResult } from "../news/fetch";
import type { StoredIdea } from "./schema";

const FORMAT_LABEL = { text: "📝 Text post", carousel: "🖼️ Carousel", video: "🎥 Video" } as const;

/** Markdown digest for a run, readable on GitHub or in any editor. */
export function renderDigest(date: string, ideas: StoredIdea[], feeds: FeedResult[]): string {
  const lines: string[] = [`# Content ideas: ${date}`, ""];
  ideas.forEach((idea, i) => {
    lines.push(`## ${i + 1}. ${idea.title}`);
    lines.push(
      `**${FORMAT_LABEL[idea.format]}** · ${idea.platforms.join(" + ")} · pillar: \`${idea.pillar}\` · for: ${idea.audience}`,
      "",
    );
    lines.push(`> ${idea.hook}`, "");
    lines.push(`**Angle:** ${idea.angle}`, "");
    lines.push(idea.format === "carousel" ? "**Slides:**" : idea.format === "video" ? "**Talking points:**" : "**Outline:**");
    idea.outline.forEach((o, n) => lines.push(`${n + 1}. ${o}`));
    lines.push("", `**Why me:** ${idea.whyMe}`, `**CTA:** ${idea.cta}`);
    if (idea.sources.length) {
      lines.push("", "**Sources:** " + idea.sources.map((s) => `[${s.title}](${s.url})`).join(" · "));
    }
    lines.push("", "---", "");
  });
  const failed = feeds.filter((f) => !f.ok);
  lines.push(
    `_Feeds: ${feeds.length - failed.length}/${feeds.length} OK, ${feeds.reduce((n, f) => n + f.count, 0)} items read. Generated by ${ideas[0]?.generatedBy ?? "n/a"}._`,
  );
  if (failed.length) {
    lines.push("", "<details><summary>Feeds that failed</summary>", "");
    failed.forEach((f) => lines.push(`- ${f.feed.name}: ${f.error}`));
    lines.push("", "</details>");
  }
  return lines.join("\n") + "\n";
}
